/** Packages under their own licence file, by id: the file (tools/packaging/licenses/) and a heading. */
export const OWN_LICENCES = {
  'ModelContextProtocol': { file: 'modelcontextprotocol-csharp-sdk.LICENSE.txt', heading: 'The MCP C# SDK (ModelContextProtocol, ModelContextProtocol.Core)' },
  'ModelContextProtocol.Core': { file: 'modelcontextprotocol-csharp-sdk.LICENSE.txt', heading: 'The MCP C# SDK (ModelContextProtocol, ModelContextProtocol.Core)' },
};

/**
 * dlls: the third-party DLL file names in the tool. packages: [{id, version, license, copyright, dlls: [file names its
 * runtime assets give]}], from the restore. licenceTexts: {file: text}. Returns {text, problems}: a DLL no package
 * gives, or a package under a licence other than MIT with no own licence file, is a problem.
 */
export function generateNotices({ dlls, packages, licenceTexts }) {
  const problems = [];
  const rows = [];
  const covered = new Set();
  for (const p of [...packages].sort((a, b) => a.id.localeCompare(b.id))) {
    const carried = p.dlls.filter((d) => dlls.includes(d)).sort();
    if (!carried.length) continue;
    carried.forEach((d) => covered.add(d));
    if (p.license !== 'MIT' && !OWN_LICENCES[p.id]) problems.push(p.id + ' ' + p.version + ': licence ' + p.license + ' has no text here (add it to OWN_LICENCES)');
    if (OWN_LICENCES[p.id] && !licenceTexts[OWN_LICENCES[p.id].file]) problems.push(p.id + ': no licence file ' + OWN_LICENCES[p.id].file);
    rows.push({ ...p, carried });
  }
  for (const d of dlls) if (!covered.has(d)) problems.push(d + ': in the tool, but no package of its restore gives it');
  const cell = (s) => String(s ?? '').replace(/\|/g, '\\|').trim();
  const lines = [
    '# Third-party notices: Isotope.UI.Mcp',
    '',
    'The `isotope-mcp` tool carries these third-party assemblies in `tools/<framework>/any/`. The Isotope code is MIT',
    '(`LICENSE`), and the upstream engine\'s licence and notices are in `licenses/microsoft-ui-reactor/`.',
    '',
    'Generated by `node tools/packaging/pack.mjs --write-notices` from the tool\'s restore and each package\'s nuspec, and',
    'checked on every pack: not edited by hand.',
    '',
    '| Package | Version | Licence | Copyright | Assemblies |',
    '|---|---|---|---|---|',
    ...rows.map((r) => '| ' + [r.id, r.version, r.license, r.copyright, r.carried.map((d) => '`' + d + '`').join(', ')].map(cell).join(' | ') + ' |'),
    '',
    '## MIT',
    '',
    'Each package above licensed MIT is under these terms, with the copyright notice in its row.',
    '',
    '```text',
    MIT_TERMS,
    '```',
  ];
  const own = [...new Set(rows.filter((r) => OWN_LICENCES[r.id]).map((r) => OWN_LICENCES[r.id].file))];
  for (const f of own) {
    const heading = Object.values(OWN_LICENCES).find((o) => o.file === f).heading;
    lines.push('', '## ' + heading, '', '```text', (licenceTexts[f] ?? '').replace(/\r\n/g, '\n').trimEnd(), '```');
  }
  return { text: lines.join('\n') + '\n', problems };
}
