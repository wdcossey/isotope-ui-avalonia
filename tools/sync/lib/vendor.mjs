// Generates the vendored tree for one upstream commit: tier 1 and 2 files, transformed, with a provenance
// header on C# files, plus a manifest and a .gitattributes that keeps the bytes exactly as generated.
// Everything is built in memory from git objects, so the cache's working tree and line endings don't matter.
import { createHash } from 'node:crypto';
import { lsTree, readBlobs, lastChanged } from './git.mjs';
import { classifyTree, isVendored } from './tiers.mjs';
import { rulesFor, applyTransforms, checkTransformTargets, unlistedMatches } from './transforms.mjs';

export const MANIFEST = 'vendored.json';
export const ATTRIBUTES = '.gitattributes';
const HEADER_EXT = /\.cs$/;

export function header({ repoName, path, lastSha, rules }) {
  return '// Vendored by tools/sync from ' + repoName + ' (MIT): ' + path + ', last changed upstream in ' + lastSha.slice(0, 12) +
    (rules.length ? '; transforms: ' + rules.map((r) => r.id).join(', ') : '') + '. Do not edit: change the tools/sync rules.';
}

/**
 * Returns {files: Map(vendor-relative path -> Buffer), manifest, classified, errors}.
 * Errors (empty includes, transforms that no longer match, undecodable files) are collected, never thrown,
 * so one run reports all of them.
 */
export function generate({ upstreamDir, commit, tierMap, transforms, repoName, repoUrl }) {
  const modes = lsTree(upstreamDir, commit);
  const tree = [...modes.keys()];
  const classified = classifyTree(tierMap, tree);
  const errors = [...classified.errors, ...checkTransformTargets(transforms, classified.byFile, new Set(tree))];
  const vendored = [];
  for (const p of tree.filter((f) => isVendored(classified.byFile.get(f)?.tier)).sort()) {
    if (p === MANIFEST || p === ATTRIBUTES) errors.push(p + ' cannot be vendored: the sync writes its own ' + p + ' there');
    else if (!/^1006[0-7]{2}$/.test(modes.get(p))) errors.push(p + ' is not a regular file (git mode ' + modes.get(p) + '), so it cannot be vendored');
    else vendored.push(p);
  }
  const blobs = readBlobs(upstreamDir, commit, vendored);
  const last = lastChanged(upstreamDir, commit, vendored);
  const files = new Map();
  const entries = [];
  for (const p of vendored) {
    const tier = classified.byFile.get(p).tier;
    const rules = tier === 2 ? rulesFor(transforms, p) : [];
    const needsText = rules.length || HEADER_EXT.test(p);
    let out = blobs.get(p);
    let text = out.toString('utf8');
    const isText = Buffer.from(text, 'utf8').equals(out);
    if (!isText && needsText) { errors.push(p + ' is not valid UTF-8, so it cannot be transformed or given a header'); continue; }
    // A rule that now matches a vendored file it doesn't list would leave that file unconverted: say so.
    if (isText) errors.push(...unlistedMatches(transforms, p, text));
    if (needsText) {
      if (rules.length) {
        const r = applyTransforms(rules, p, text);
        errors.push(...r.errors);
        text = r.text;
      }
      if (HEADER_EXT.test(p)) {
        const bom = text.startsWith('\u{FEFF}') ? '\u{FEFF}' : '';
        const eol = text.includes('\r\n') ? '\r\n' : '\n';
        text = bom + header({ repoName, path: p, lastSha: last.get(p), rules }) + eol + text.slice(bom.length);
      }
      out = Buffer.from(text, 'utf8');
    }
    files.set(p, out);
    entries.push({ path: p, tier, lastChanged: last.get(p), transforms: rules.map((r) => r.id), sha256: createHash('sha256').update(out).digest('hex') });
  }
  const manifest = { generatedBy: 'tools/sync', repo: repoUrl, commit, files: entries };
  files.set(MANIFEST, Buffer.from(JSON.stringify(manifest, null, 2) + '\n', 'utf8'));
  files.set(ATTRIBUTES, Buffer.from('# Generated by tools/sync: vendored bytes are checked out exactly as generated.\n* -text\n', 'utf8'));
  return { files, manifest, classified, errors };
}
